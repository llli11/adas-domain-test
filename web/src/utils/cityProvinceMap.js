const RE = /市|省|自治区|特别行政区|自治州|地区|盟/g

export function checkCityInArea(city, area) {
  if (!city || !area) return true
  const nc = String(city).replace(RE, '').trim()
  if (!nc) return true
  const mp = CITY_PROVINCE_MAP[nc] || ''
  let parts = String(area).split(/[、，,\/\s·•|｜]+/)
  if (parts.length===1 && parts[0].length>4) {
    const r=parts[0]; parts=[]; for(let i=0;i<r.length;i+=2) parts.push(r.substring(i,Math.min(i+2,r.length)))
  }
  for (const p of parts) {
    const pp = p.replace(RE,'').trim()
    if (!pp) continue
    if (pp===nc||nc===pp||pp.includes(nc)||nc.includes(pp)) return true
    if (mp&&pp===mp) return true
    if (!mp&&pp.length<=3&&nc.length>=2) return true
  }
  return false
}

export function isAreaMismatch(vehicle) {
  const city = (vehicle.test_city||'').replace(RE,'').trim()
  const area = vehicle.temp_plate_area||vehicle.insurance_area||''
  return !checkCityInArea(city, area)
}
